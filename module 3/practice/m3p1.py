pizza_price = float(input("Введіть ціну піци: "))
pizza_count = int(input("введіть колво. піци: "))
wallet = float(input("Введіть весь ваш рахунок: "))
total_cost = pizza_price * pizza_count
if wallet >= total_cost:
    print("Грошей вистачає")
else:
    shortage = total_cost - wallet
    print(f"на вашому рахунку не вистачає коштів, а саме {shortage}")