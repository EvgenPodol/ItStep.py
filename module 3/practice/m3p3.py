# Користувач вводить швидкість.
# Якщо швидкість більша за 90км\год – спитати де саме
# він
# їде: місто чи траса. Якщо в місті то повідомити про
# штраф, якщо траса то попередження
# Якщо швидкість менша за 20км/год – спитати скільки
# років машині. Якщо їй більше 15 років – запропонувати
# купити нову, інакше запропонувати поїхати на СТО
# Інша швидкість – побажати гарної подорожі.

speed = float(input("Введіть вашу швидкість: "))

if speed > 90:
    where_u = input("Де ви їдете? місто/траса:")
    if where_u == "місто":
        print("Вам нарахований штраф!")
    elif where_u == "траса":
        print("Попередження за велику швидкість.")
elif speed < 20:
    age_car = int(input("скільки років машині: "))
    if age_car > 15:
        print("Запропоную вам купити нову машину!")
    else:
        print("Запропоную вам з'їхати на СТО")
else:
    print("Бажаю гарної дороги!")