# Завдання 2
# Троє друзів пішли на рибалку. Програма отримує кількість риби яку зловив кожен рибалка.
# Виведіть на екран:
# ● скільки в середньому вийшло риб на людину
# ● розмір найбільшого улову
fish1 = int(input("Введіть скільки риби зловив 1 людина:"))
fish2 = int(input("Введіть скільки риби зловила 2 людина:"))
fish3 = int(input("Введіть скільки риби зловила 3 людина:"))
average_fish = (fish1+fish2+fish3) / 3
max_catch = max(fish1, fish2, fish3)
print(f"Средньому риб на людину: {average_fish}")
print(f"Розмір найбільшого улову: {max_catch} ")

